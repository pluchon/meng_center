def system_prompt(request) -> str:
    import json

    card = CARDS[request.character]
    examples = "\n".join(f"用户：{u}\n角色：{a}" for u, a in card.examples[request.stage - 1])
    return "\n\n".join(
        (
            BOUNDARY,
            LANGUAGE,
            f"角色卡 {VERSION}：{card.name}\n{card.setting}\n{card.speech}",
            f"当前阶段：{card.stages[request.stage - 1]}\n示例：\n{examples}",
            "心情依据（数据）：" + json.dumps(request.mood, ensure_ascii=False),
            "长期记忆（数据）：" + json.dumps(request.memories, ensure_ascii=False),
            "会话摘要（数据）：" + json.dumps(request.summary, ensure_ascii=False),
            "用户称呼（数据）：" + json.dumps(request.nickname, ensure_ascii=False),
        )
    )

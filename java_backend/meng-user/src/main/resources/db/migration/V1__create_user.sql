CREATE TABLE user (
  id BIGINT NOT NULL AUTO_INCREMENT,
  username VARCHAR(32) NOT NULL,
  email_cipher VARCHAR(1024) NULL,
  email_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  phone_cipher VARCHAR(1024) NULL,
  phone_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
  password_hash VARCHAR(100) NOT NULL,
  nickname VARCHAR(64) NULL,
  avatar VARCHAR(512) NULL,
  role VARCHAR(16) NOT NULL,
  status VARCHAR(16) NOT NULL,
  apply_reason VARCHAR(200) NULL,
  reject_reason VARCHAR(200) NULL,
  level INT NOT NULL DEFAULT 0,
  create_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
  update_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
  delete_state TINYINT NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY uk_user_username (username),
  UNIQUE KEY uk_user_email_hash (email_hash),
  UNIQUE KEY uk_user_phone_hash (phone_hash),
  KEY idx_user_status_created (status, create_time, id),
  CONSTRAINT ck_user_role CHECK (role IN ('USER', 'ADMIN')),
  CONSTRAINT ck_user_status CHECK (status IN ('PENDING', 'NORMAL', 'REJECTED')),
  CONSTRAINT ck_user_one_contact CHECK (email_hash IS NULL OR phone_hash IS NULL),
  CONSTRAINT ck_user_email_pair CHECK ((email_hash IS NULL) = (email_cipher IS NULL)),
  CONSTRAINT ck_user_phone_pair CHECK ((phone_hash IS NULL) = (phone_cipher IS NULL))
) CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;

ALTER TABLE user ADD COLUMN profile_version DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6);
CREATE TABLE profile_ai_review (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT NOT NULL,
 profile_version DATETIME(6) NOT NULL,
 verdict VARCHAR(16) NOT NULL,
 labels JSON NOT NULL,
 reason VARCHAR(200) NOT NULL,
 model_version VARCHAR(255) NOT NULL,
 original_nickname VARCHAR(100),
 original_signature VARCHAR(200),
 original_avatar VARCHAR(255),
 avatar_review JSON,
 review_state VARCHAR(20) NOT NULL DEFAULT 'UNHANDLED',
 create_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 update_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 delete_state TINYINT NOT NULL DEFAULT 0,
 UNIQUE KEY uk_profile_review(user_id,profile_version)
);
CREATE TABLE profile_ai_outbox (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 event_id VARCHAR(64) NOT NULL UNIQUE,
 body MEDIUMTEXT NOT NULL,
 sent TINYINT NOT NULL DEFAULT 0,
 create_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
 update_time DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
 delete_state TINYINT NOT NULL DEFAULT 0,
 INDEX idx_profile_outbox(sent,create_time)
);

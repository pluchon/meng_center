ALTER TABLE post ADD COLUMN cover_image_id BIGINT NULL;
ALTER TABLE post_image ADD COLUMN kind VARCHAR(20) NOT NULL DEFAULT 'ATTACHMENT';
CREATE TABLE tag (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(48) NOT NULL, name_key VARCHAR(48) NOT NULL,
 use_count BIGINT NOT NULL DEFAULT 0, create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 delete_state INT NOT NULL DEFAULT 0, UNIQUE KEY uk_name_key(name_key)
) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin;
CREATE TABLE post_tag (
 post_id BIGINT NOT NULL, tag_id BIGINT NOT NULL, create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(post_id,tag_id), INDEX idx_tag_post(tag_id,post_id)
);
CREATE TABLE post_draft (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, author_id BIGINT NOT NULL, category VARCHAR(20), title VARCHAR(50), content TEXT,
 image_ids JSON NOT NULL, cover_image_id BIGINT, tags JSON NOT NULL,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 delete_state INT NOT NULL DEFAULT 0, INDEX idx_author_id(author_id,id)
) CHARACTER SET utf8mb4;
CREATE TABLE post_draft_owner (
 author_id BIGINT PRIMARY KEY
);
